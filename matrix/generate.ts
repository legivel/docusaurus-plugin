rmSync(ROOT, { recursive: true, force: true });
for (const site of sites) {
  const dir = join(ROOT, site.name);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "docusaurus.config.js"), config(site));
  writeFileSync(join(dir, "sidebars.js"), site.sidebars ?? `module.exports = {};`);
  writeFileSync(join(dir, "package.json"), JSON.stringify({ name: `matrix-${site.name}`, private: true }));
  writeFileSync(join(dir, ".gitignore"), "build\n.docusaurus\n");
  writeFileSync(join(dir, "SHAPE.txt"), site.shape);
  for (const [path, content] of Object.entries(site.files)) {
    mkdirSync(join(dir, path, ".."), { recursive: true });
    writeFileSync(join(dir, path), content);
  }
}
