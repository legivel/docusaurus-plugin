/**
 * The simulated Docusaurus sites of the test matrix: one folder per shape under matrix/sites/, each a
 * small site that uses the plugin from ../../dist. `bun matrix/generate.ts`
 * writes them; `matrix/run.sh` builds each against a test API and collects
 * the results. The sites are generated, never edited by hand.
 */
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("./sites/", import.meta.url).pathname;

interface Site {
  name: string;
  /** What the shape tests, for the results table. */
  shape: string;
  config: Record<string, unknown>;
  plugin: Record<string, unknown>;
  sidebars?: string;
  files: Record<string, string>;
  /** Extra top-level config lines (i18n, presets options). */
  extra?: string;
}

/** The matrix builds against a test API; a build without LEGIVEL_API_URL stops instead of reaching production. */
const API_URL = 'process.env.LEGIVEL_API_URL || (() => { throw new Error("set LEGIVEL_API_URL to the test API origin"); })()';
const PLUGIN = (options: Record<string, unknown>) => `[require.resolve("../../../dist/index.js"), ${JSON.stringify({ apiUrl: "API_URL", ...options }).replace('"API_URL"', API_URL)}]`;

function config(site: Site): string {
  const docs = (site.config.docs as Record<string, unknown> | undefined) ?? { sidebarPath: "./sidebars.js" };
  const i18n = site.config.i18n ? `i18n: ${JSON.stringify(site.config.i18n)},` : "";
  return `module.exports = {
  title: ${JSON.stringify(site.config.title ?? `Matrix: ${site.name}`)},
  tagline: ${JSON.stringify(site.config.tagline ?? site.shape)},
  url: "https://matrix.example.com",
  baseUrl: ${JSON.stringify(site.config.baseUrl ?? "/")},
  onBrokenLinks: "warn",
  onBrokenMarkdownLinks: "warn",
  ${i18n}
  presets: [["classic", { docs: ${JSON.stringify(docs)}, blog: false, pages: false }]],
  plugins: [${PLUGIN(site.plugin)}],
  themeConfig: { navbar: { title: ${JSON.stringify(site.name)} } },
  ${site.extra ?? ""}
};
`;
}

